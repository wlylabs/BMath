// Writes out/sw.js after `next build`: precaches every exported page, the RSC
// payloads client-side navigation fetches between them, and the static assets,
// so the whole app opens and navigates offline. Live market APIs are never cached.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const OUT = 'out';
const SHELL = ['/manifest.webmanifest', '/icon.svg', '/apple-icon.png', '/favicon.ico', '/icon-192.png', '/icon-512.png', '/icon-maskable-512.png'];

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat();
}

const toUrl = (file) => '/' + relative(OUT, file).split(sep).join('/');

const SKIP = /^\/(_not-found|404)(\/|\.html$)/;

const all = await walk(OUT);
const urls = all.map(toUrl);
const exists = new Set(urls);
// /fee/index.html is served as /fee/
const pages = urls.filter((u) => u.endsWith('/index.html') && !SKIP.test(u)).map((u) => u.slice(0, -'index.html'.length));
const payloads = urls.filter((u) => u.endsWith('.txt') && u !== '/robots.txt' && !SKIP.test(u));
const statics = urls.filter((u) => u.startsWith('/_next/static/') && !u.endsWith('.map'));
const shell = SHELL.filter((u) => exists.has(u));
const precache = [...pages, ...payloads, ...shell, ...statics].sort();

const hash = createHash('sha256');
for (const url of precache) {
  const file = url.endsWith('/') ? join(OUT, ...url.slice(1).split('/'), 'index.html') : join(OUT, ...url.slice(1).split('/'));
  hash.update(url).update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 12);

const sw = `/* BMath service worker ${version}. Generated by scripts/build-sw.mjs; do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'bmath-' + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const PAGES = new Set(${JSON.stringify(pages)});

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith('bmath-') && k !== CACHE).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

async function fromCache(request) {
  const cache = await caches.open(CACHE);
  return cache.match(request, { ignoreSearch: true });
}

async function put(request, response) {
  if (!response || !response.ok || response.type !== 'basic') return response;
  const cache = await caches.open(CACHE);
  await cache.put(request, response.clone());
  return response;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // live prices and outbound links always go to the network
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // network first so a deploy shows up right away; the cached page when offline
    const page = url.pathname.endsWith('/') ? url.pathname : url.pathname + '/';
    event.respondWith(
      fetch(request)
        .then((res) => (PAGES.has(page) ? put(new Request(page), res) : res))
        .catch(
          async () =>
            (await fromCache(new Request(PAGES.has(page) ? page : url.pathname))) ||
            (await fromCache(new Request('/'))) ||
            Response.error(),
        ),
    );
    return;
  }

  if (url.pathname.startsWith('/_next/static/')) {
    // content-hashed files never change
    event.respondWith(fromCache(request).then((hit) => hit || fetch(request).then((res) => put(request, res))));
    return;
  }

  if (url.pathname.endsWith('.txt')) {
    // RSC payloads name the build they belong to: network first, or after a deploy every
    // in-app navigation would fetch an old build's payload and fall back to a full reload.
    // Keyed by path (the _rsc query is a cache-buster) so the fresh copy replaces the precached one.
    const key = new Request(url.origin + url.pathname);
    event.respondWith(
      fetch(request)
        .then((res) => put(key, res))
        .catch(async () => (await fromCache(key)) || Response.error()),
    );
    return;
  }

  // icons, manifest and the rest: serve cached, refresh in the background
  event.respondWith(
    fromCache(request).then((hit) => {
      const network = fetch(request)
        .then((res) => put(request, res))
        .catch(() => hit);
      return hit || network;
    }),
  );
});
`;

await writeFile(join(OUT, 'sw.js'), sw);
console.log(`sw.js ${version}: ${pages.length} pages, ${payloads.length} payloads, ${precache.length} files precached`);
