// Writes public/sw.js before `next build`. It precaches every page and the app icons, caches the
// content-hashed /_next/static files as they load, and keeps a copy of each page and its RSC
// payload so the app opens and navigates offline. /api/ (live Bordrless data) is never touched.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const SHELL = ['/manifest.webmanifest', '/icon.svg', '/apple-icon.png', '/favicon.ico', '/icon-192.png', '/icon-512.png', '/icon-maskable-512.png'];

// the pages, from the one list the app routes by
const routes = await readFile('src/lib/routes.ts', 'utf8');
const block = routes.slice(routes.indexOf('export const ROUTES'), routes.indexOf('} as const'));
const pages = [...block.matchAll(/:\s*'([^']+)'/g)].map((m) => m[1]);
if (!pages.includes('/')) throw new Error('could not read ROUTES from src/lib/routes.ts');

// a new version whenever anything that ships changes, so clients pick up a deploy
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat();
}
const hash = createHash('sha256');
for (const file of [...(await walk('src')), ...(await walk('public')), 'package-lock.json'].filter((f) => !f.endsWith('sw.js')).sort()) {
  hash.update(file).update(await readFile(file));
}
const version = process.env.VERCEL_GIT_COMMIT_SHA?.slice(0, 12) || hash.digest('hex').slice(0, 12);
const precache = [...pages, ...SHELL];

const sw = `/* BMath service worker ${version}. Generated by scripts/build-sw.mjs; do not edit. */
const CACHE = 'bmath-${version}';
const PRECACHE = ${JSON.stringify(precache)};
const PAGES = new Set(${JSON.stringify(pages)});

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith('bmath-') && k !== CACHE).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

async function fromCache(key) {
  return (await caches.open(CACHE)).match(key);
}

async function put(key, response) {
  if (!response || !response.ok || response.type !== 'basic') return response;
  await (await caches.open(CACHE)).put(key, response.clone());
  return response;
}

// network first, a cached copy when offline
function networkFirst(event, key, fallback) {
  event.respondWith(
    fetch(event.request)
      .then((res) => put(key, res))
      .catch(async () => (await fromCache(key)) || (fallback && (await fromCache(fallback))) || Response.error()),
  );
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // outbound links, and live data from /api/, always go to the network untouched
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  const page = url.pathname.endsWith('/') ? url.pathname : url.pathname + '/';

  // a client-side navigation's RSC payload: kept apart from the page's HTML under its own key
  if (request.headers.get('RSC') === '1' || url.searchParams.has('_rsc')) {
    if (PAGES.has(page)) networkFirst(event, new Request(url.origin + page + '?__rsc'));
    return;
  }

  if (request.mode === 'navigate') {
    networkFirst(event, new Request(PAGES.has(page) ? page : url.pathname), new Request('/'));
    return;
  }

  if (url.pathname.startsWith('/_next/static/')) {
    // content-hashed files never change
    event.respondWith(fromCache(request).then((hit) => hit || fetch(request).then((res) => put(request, res))));
    return;
  }

  if (PRECACHE.includes(url.pathname)) {
    // icons and the manifest: serve cached, refresh in the background
    event.respondWith(
      fromCache(request).then((hit) => {
        const network = fetch(request)
          .then((res) => put(request, res))
          .catch(() => hit);
        return hit || network;
      }),
    );
  }
});
`;

await writeFile('public/sw.js', sw);
console.log(`sw.js ${version}: ${pages.length} pages, ${precache.length} files precached`);
