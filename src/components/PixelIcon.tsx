export type PixelIconName = keyof typeof GRIDS;

const PATHS = Object.fromEntries(
  Object.entries(GRIDS).map(([name, rows]) => {
    let d = '';
    rows.forEach((row, y) => {
      for (let x = 0; x < 12; x++) {
        if (row[x] !== '#') continue;
        let end = x;
        while (end + 1 < 12 && row[end + 1] === '#') end++;
        d += `M${x} ${y}h${end - x + 1}v1H${x}z`;
        x = end;
      }
    });
    return [name, d];
  }),
) as Record<PixelIconName, string>;

export function PixelIcon({ name, className }: { name: PixelIconName; className?: string }) {
  return (
    <svg viewBox="0 0 12 12" aria-hidden fill="currentColor" className={cx('pixel shrink-0', className ?? 'size-4')}>
      <path d={PATHS[name]} />
    </svg>
  );
}
